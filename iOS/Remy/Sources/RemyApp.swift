import SwiftUI

@main struct RemyApp: App {
    @StateObject private var model = AppModel()
    @Environment(\.scenePhase) private var phase
    init() {
        // Sheet and list titles in Google Sans Flex, matching the rest of the app.
        let bar = UINavigationBar.appearance()
        if let title = UIFont(name: "GoogleSansFlex-Medium", size: 17) { bar.titleTextAttributes = [.font: title] }
        if let large = UIFont(name: "GoogleSansFlex-Regular", size: 32) { bar.largeTitleTextAttributes = [.font: large] }
    }
    var body: some Scene {
        WindowGroup {
            ContentView(model: model)
                .preferredColorScheme(.dark)
                .task {
                    UIApplication.shared.isIdleTimerDisabled = true
                    let arguments = ProcessInfo.processInfo.arguments
                    if arguments.contains("--detector-benchmark") { await FastObjectDetector.benchmark(); return }
                    if arguments.contains("--ingredient-model-probe") { await RemyEval.ingredientModelProbe(); return }
                    if arguments.contains("--ingredient-first-smoke") {
                        for _ in 0..<600 where model.models.isWorking { try? await Task.sleep(for: .milliseconds(200)) }
                        await model.ingredientFirstSmoke()
                        return
                    }
                    if arguments.contains("--stability-smoke") || arguments.contains("--stability-camera-smoke") {
                        for _ in 0..<600 where model.models.isWorking { try? await Task.sleep(for: .milliseconds(200)) }
                        await model.stabilitySmoke(withCamera: arguments.contains("--stability-camera-smoke"))
                        return
                    }
                    if arguments.contains("--hands-smoke") {
                        model.startPhoneCamera()
                        return
                    }
                    let cameraTest = arguments.contains("--camera-smoke")
                    let boardTest = arguments.contains("--board-smoke")
                    let promptEval = arguments.contains("--prompt-eval")
                    guard arguments.contains("--local-smoke") || cameraTest || boardTest || promptEval else {
                        // Hands-free means no setup tap: once the downloaded model is verified, load it, which also
                        // turns the microphone on. Before this, every launch started with the mic off.
                        for _ in 0..<600 where model.models.isWorking { try? await Task.sleep(for: .milliseconds(200)) }
                        if model.models.modelURL != nil, !model.isLoaded, !model.isLoading { await model.loadModel() }
                        return
                    }
                    // Device-only smoke entry point: the output is generated by the actual local model.
                    for _ in 0..<600 where model.models.isWorking {
                        try? await Task.sleep(for: .milliseconds(200))
                    }
                    if promptEval {
                        // --with-camera measures Gemma while the camera and GPU hand tracking compete for the phone.
                        if arguments.contains("--with-camera") { model.startPhoneCamera(); try? await Task.sleep(for: .seconds(3)) }
                        // Runs its own engine on photos in Documents/Eval; the app's model stays unloaded.
                        if let url = model.models.modelURL { await RemyEval.run(modelPath: url.path) }
                        return
                    }
                    await model.loadModel()
                    if cameraTest || boardTest {
                        model.startPhoneCamera()
                        for _ in 0..<150 {
                            if model.frame != nil { break }
                            try? await Task.sleep(for: .milliseconds(200))
                        }
                        if boardTest {
                            // Collect a real chronological camera sequence before the structured check.
                            try? await Task.sleep(for: .seconds(1))
                            await model.reviewBoard()
                        } else { await model.smokeTest(withCamera: true) }
                    } else { await model.smokeTest(withCamera: false) }
                    print("REMY_DEVICE_SMOKE: \(model.status)")
                    print(model.rawResponse)
                    if let receipt = model.receiptURL { print("RECEIPT: \(receipt.lastPathComponent)") }
                }
                .onChange(of: phase) { _, value in
                    if value == .active { UIApplication.shared.isIdleTimerDisabled = true }
                    if value == .background { UIApplication.shared.isIdleTimerDisabled = false }
                    // Permission sheets temporarily make the scene inactive. Only leaving the app pauses capture.
                    model.sceneChanged(value)
                }
        }
    }
}
